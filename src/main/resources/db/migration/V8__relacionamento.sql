CREATE TABLE chat_campanha (
    id UUID PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresa(id),
    nome VARCHAR(120) NOT NULL,
    canal_id UUID NOT NULL,
    lista_id BIGINT NOT NULL,
    modelo_id BIGINT,
    texto TEXT,
    estado VARCHAR(20) NOT NULL DEFAULT 'RASCUNHO'
        CHECK (estado IN ('RASCUNHO','AGENDADA','EXECUTANDO','PAUSADA','CONCLUIDA','CANCELADA')),
    agendada_em TIMESTAMPTZ,
    intervalo_segundos INTEGER NOT NULL DEFAULT 5 CHECK (intervalo_segundos > 0),
    criada_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    iniciada_em TIMESTAMPTZ,
    concluida_em TIMESTAMPTZ,
    proximo_envio_em TIMESTAMPTZ,
    CHECK (texto IS NOT NULL OR modelo_id IS NOT NULL),
    FOREIGN KEY (canal_id, empresa_id) REFERENCES chat_canal(id, empresa_id),
    FOREIGN KEY (lista_id, empresa_id) REFERENCES chat_lista_contatos(id, empresa_id),
    FOREIGN KEY (modelo_id, empresa_id) REFERENCES chat_modelo_mensagem(id, empresa_id),
    UNIQUE(id, empresa_id)
);
