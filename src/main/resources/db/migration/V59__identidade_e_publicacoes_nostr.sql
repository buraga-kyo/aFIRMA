CREATE TABLE firma_nostr_configuracao (
 empresa_id BIGINT PRIMARY KEY REFERENCES "Empresas"("EmpresaId"),
 chave_publica CHAR(64) NOT NULL,
 referencia VARCHAR(80) NOT NULL,
 nome VARCHAR(100) NOT NULL,
 sobre VARCHAR(500) NOT NULL,
 ativa BOOLEAN NOT NULL DEFAULT FALSE,
 atualizado_por TEXT NOT NULL,
 atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE firma_nostr_publicacao (
 id UUID PRIMARY KEY,
 empresa_id BIGINT NOT NULL REFERENCES "Empresas"("EmpresaId"),
 chave_publica CHAR(64) NOT NULL,
 referencia VARCHAR(80) NOT NULL,
 tipo VARCHAR(20) NOT NULL CHECK(tipo IN ('PERFIL','COMPROVANTE')),
 deduplicacao VARCHAR(100) NOT NULL,
 pedido JSONB NOT NULL,
 evento_canonico TEXT,
 evento_id CHAR(64),
 publicacao_estado VARCHAR(30) NOT NULL DEFAULT 'PENDENTE',
 anterioridade_estado VARCHAR(30) NOT NULL DEFAULT 'PENDENTE',
 relays JSONB NOT NULL DEFAULT '[]',
 ots BYTEA,
 bloco CHAR(64),
 altura BIGINT,
 data_bloco BIGINT,
 tentativas INTEGER NOT NULL DEFAULT 0,
 proxima_tentativa TIMESTAMPTZ NOT NULL DEFAULT now(),
 lease UUID,
 lease_ate TIMESTAMPTZ,
 erro_codigo VARCHAR(80),
 criado_por TEXT NOT NULL,
 criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
 atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(empresa_id,tipo,deduplicacao)
);
CREATE INDEX firma_nostr_fila ON firma_nostr_publicacao(proxima_tentativa) WHERE anterioridade_estado <> 'CONFIRMADA' OR publicacao_estado <> 'PUBLICADO';
CREATE TABLE firma_nostr_auditoria (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id BIGINT NOT NULL REFERENCES "Empresas"("EmpresaId"),
 acao VARCHAR(40) NOT NULL,
 chave_publica CHAR(64),
 responsavel TEXT NOT NULL,
 criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
