CREATE FUNCTION firma_autentica_metricas() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE assumido TIMESTAMPTZ; respostas RECORD;
BEGIN
 IF NEW."AtendimentoStatus"='finalizado' THEN
  NEW."AtendimentoDataFinalizado"=COALESCE(NEW."AtendimentoDataFinalizado",now());
  NEW."AtendimentoContextoIA"=NULL;
  NEW."AtendimentoDuracao"=GREATEST(0,floor(extract(epoch FROM NEW."AtendimentoDataFinalizado"-NEW."createdAt")))::integer;
  SELECT min("createdAt") INTO assumido FROM autentica."AtendimentoAcao" WHERE "AtendimentoId"=NEW.id AND "AtendimentoAcaoTipo" IN ('Assumir','assumir');
  NEW."AtendimentoTempoPendente"=CASE WHEN NEW."AtendimentoBOTExterno" THEN 0 WHEN assumido IS NOT NULL THEN GREATEST(0,floor(extract(epoch FROM assumido-NEW."createdAt")))::integer WHEN NOT EXISTS(SELECT 1 FROM autentica."AtendimentoAcao" WHERE "AtendimentoId"=NEW.id) THEN NEW."AtendimentoDuracao" ELSE 0 END;
  SELECT NOT COALESCE("MensagemFromMe",false) INTO NEW."AtendimentoReceptivo" FROM autentica."Mensagem" WHERE "AtendimentoId"=NEW.id ORDER BY id LIMIT 1;
  SELECT COALESCE(sum(dt) FILTER(WHERE NOT enviada AND proxima AND atendente),0) soma_atendente,
    count(*) FILTER(WHERE NOT enviada AND proxima AND atendente) qtd_atendente,
    COALESCE(sum(dt) FILTER(WHERE enviada AND NOT proxima AND atual_atendente),0) soma_cliente,
    count(*) FILTER(WHERE NOT enviada)+count(*) FILTER(WHERE enviada AND NOT proxima AND atual_atendente) qtd_cliente
  INTO respostas FROM (
    SELECT COALESCE("MensagemFromMe",false) enviada,"MensagemEnviadaPeloAtendente" atual_atendente,
      lead("MensagemFromMe") OVER w proxima,lead("MensagemEnviadaPeloAtendente") OVER w atendente,
      GREATEST(0,extract(epoch FROM lead("createdAt") OVER w-"createdAt")) dt
    FROM autentica."Mensagem" WHERE "AtendimentoId"=NEW.id WINDOW w AS(ORDER BY id)
  ) mensagens;
  NEW."AtendimentoTempoRespostaAtendente"=floor(respostas.soma_atendente/GREATEST(respostas.qtd_atendente,1))::integer;
  NEW."AtendimentoTempoRespostaCliente"=floor(respostas.soma_cliente/GREATEST(respostas.qtd_cliente,1))::integer;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER firma_autentica_metricas BEFORE UPDATE OF "AtendimentoStatus" ON autentica."Atendimento" FOR EACH ROW EXECUTE FUNCTION firma_autentica_metricas();

CREATE TABLE firma_autentica_webhook_entrega (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 webhook_id INTEGER NOT NULL REFERENCES autentica."Webhook"(id) ON DELETE CASCADE,
 cliente_id INTEGER NOT NULL REFERENCES autentica."Cliente"(id),
 evento TEXT NOT NULL,dados JSONB NOT NULL,
 estado TEXT NOT NULL DEFAULT 'PENDENTE',tentativas INTEGER NOT NULL DEFAULT 0,
 proxima_tentativa TIMESTAMPTZ NOT NULL DEFAULT now(),
 codigo INTEGER,erro TEXT,criada_em TIMESTAMPTZ NOT NULL DEFAULT now(),respondida_em TIMESTAMPTZ
);
CREATE INDEX firma_autentica_webhook_fila ON firma_autentica_webhook_entrega(estado,proxima_tentativa);
CREATE FUNCTION firma_autentica_evento() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE canal INTEGER; cliente INTEGER; evento TEXT; dados JSONB;
BEGIN
 IF TG_TABLE_NAME='Mensagem' THEN
  IF COALESCE(NEW."MensagemFromMe",false) THEN RETURN NEW; END IF;
  canal=NEW."CanalId";evento='mensagem_recebida';dados=to_jsonb(NEW)-'MensagemRAW'-'MensagemKeyWhatsApp';
 ELSIF TG_TABLE_NAME='Canal' THEN
  IF NEW."CanalStatus" IS NOT DISTINCT FROM OLD."CanalStatus" THEN RETURN NEW; END IF;
  canal=NEW.id;evento='status_canal';dados=jsonb_build_object('CanalId',NEW.id,'CanalGUID',NEW."CanalGUID",'CanalNome',NEW."CanalNome",'CanalStatus',NEW."CanalStatus");
 ELSE
  IF NOT COALESCE(OLD."AtendimentoBOTExterno",false) OR COALESCE(NEW."AtendimentoBOTExterno",false) THEN RETURN NEW; END IF;
  canal=NEW."CanalId";evento='chatbot_externo_assumido';dados=jsonb_build_object('AtendimentoId',NEW.id,'ContatoId',NEW."ContatoId",'CanalId',canal);
 END IF;
 SELECT "ClienteId" INTO cliente FROM autentica."Canal" WHERE id=canal;
 -- Registros antigos já têm entrega pelo executor anterior; os novos usam este contrato.
 INSERT INTO firma_autentica_webhook_entrega(webhook_id,cliente_id,evento,dados)
 SELECT w.id,cliente,evento,jsonb_build_object('Evento',evento,'Dados',dados || jsonb_build_object('ClienteId',cliente,'CanalId',canal)) FROM autentica."Webhook" w
 WHERE w."ClienteId"=cliente AND w."WebhookEvento"=evento AND (w."WebhookTodosCanais" OR w."CanalId"=canal)
 AND NOT EXISTS(SELECT 1 FROM firma_autentica_vinculo v WHERE v.destino='Webhook' AND v.destino_id=w.id);
 RETURN NEW;
END $$;
CREATE TRIGGER firma_autentica_evento_mensagem AFTER INSERT ON autentica."Mensagem" FOR EACH ROW EXECUTE FUNCTION firma_autentica_evento();
CREATE TRIGGER firma_autentica_evento_canal AFTER UPDATE OF "CanalStatus" ON autentica."Canal" FOR EACH ROW EXECUTE FUNCTION firma_autentica_evento();
CREATE TRIGGER firma_autentica_evento_bot AFTER UPDATE OF "AtendimentoBOTExterno" ON autentica."Atendimento" FOR EACH ROW EXECUTE FUNCTION firma_autentica_evento();
