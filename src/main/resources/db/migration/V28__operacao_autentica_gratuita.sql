-- A FIRMA é gratuita. Os registros históricos de planos permanecem para auditoria.
DROP TRIGGER IF EXISTS chat_canal_limite ON chat_canal;
DROP TRIGGER IF EXISTS chat_atendente_limite ON chat_atendente;

-- Estado operacional fora do contrato original: agenda durável, sem alterar suas 33 tabelas.
CREATE TABLE firma_autentica_disparo (
  disparo_id INTEGER PRIMARY KEY REFERENCES autentica."DisparoMassa"(id) ON DELETE CASCADE,
  proximo_envio TIMESTAMPTZ NOT NULL DEFAULT now(),
  dia DATE, enviados_dia INTEGER NOT NULL DEFAULT 0,
  lote INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE firma_autentica_envio (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id INTEGER NOT NULL REFERENCES autentica."Cliente"(id),
  disparo_id INTEGER REFERENCES autentica."DisparoMassa"(id) ON DELETE CASCADE,
  atendimento_id INTEGER REFERENCES autentica."Atendimento"(id) ON DELETE SET NULL,
  canal_id INTEGER NOT NULL REFERENCES autentica."Canal"(id),
  destinatario TEXT NOT NULL,
  texto TEXT,
  modelo_id INTEGER REFERENCES autentica."MensagemTemplate"(id),
  arquivo_id INTEGER REFERENCES autentica."Arquivo"(id),
  variaveis JSONB NOT NULL DEFAULT '[]',
  indice INTEGER,
  estado TEXT NOT NULL DEFAULT 'PENDENTE' CHECK(estado IN ('PENDENTE','ENVIANDO','ENVIADO','FALHOU','CANCELADO','INCERTO')),
  externo TEXT, erro TEXT,
  criada_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  atualizada_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(disparo_id,indice)
);
CREATE INDEX firma_autentica_envio_fila ON firma_autentica_envio(estado,criada_em);
CREATE TABLE firma_autentica_segredo (
  cliente_id INTEGER NOT NULL REFERENCES autentica."Cliente"(id),
  tipo TEXT NOT NULL,
  registro_id INTEGER NOT NULL,
  valor TEXT NOT NULL,
  PRIMARY KEY(cliente_id,tipo,registro_id)
);
-- Chaves UUID do contrato Autentica são emitidas somente pelo servidor.
CREATE UNIQUE INDEX IF NOT EXISTS firma_autentica_chave_valor ON autentica."ChaveAPI"("ChaveAPIValor");
