CREATE TABLE chat_setor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL UNIQUE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE chat_atendente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identidade VARCHAR(200) NOT NULL UNIQUE,
    nome VARCHAR(100) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    disponibilidade VARCHAR(20) NOT NULL DEFAULT 'AUSENTE'
        CHECK (disponibilidade IN ('DISPONIVEL', 'OCUPADO', 'AUSENTE'))
);

CREATE TABLE chat_atendente_setor (
    atendente_id BIGINT NOT NULL REFERENCES chat_atendente(id) ON DELETE CASCADE,
    setor_id BIGINT NOT NULL REFERENCES chat_setor(id),
    PRIMARY KEY (atendente_id, setor_id)
);

CREATE TABLE chat_canal (
    id UUID PRIMARY KEY,
    nome VARCHAR(80) NOT NULL,
    telefone VARCHAR(30) NOT NULL UNIQUE,
    setor_padrao_id BIGINT REFERENCES chat_setor(id),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    conexao VARCHAR(20) NOT NULL DEFAULT 'DESCONECTADO'
        CHECK (conexao IN ('DESCONECTADO', 'CONECTANDO', 'CONECTADO', 'QR_PENDENTE')),
    mensagem_encerramento TEXT,
    inatividade_minutos INTEGER CHECK (inatividade_minutos IS NULL OR inatividade_minutos > 0),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE chat_contato (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telefone VARCHAR(30) NOT NULL UNIQUE,
    nome VARCHAR(100),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE chat_atendimento (
    id UUID PRIMARY KEY,
    canal_id UUID NOT NULL REFERENCES chat_canal(id),
    contato_id BIGINT NOT NULL REFERENCES chat_contato(id),
    setor_id BIGINT REFERENCES chat_setor(id),
    atendente_id BIGINT REFERENCES chat_atendente(id),
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('PENDENTE', 'EM_ANDAMENTO', 'FINALIZADO')),
    iniciado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finalizado_em TIMESTAMPTZ,
    CHECK ((estado = 'PENDENTE' AND atendente_id IS NULL)
        OR (estado = 'EM_ANDAMENTO' AND atendente_id IS NOT NULL)
        OR estado = 'FINALIZADO')
);
CREATE UNIQUE INDEX chat_atendimento_aberto_unico
    ON chat_atendimento(canal_id, contato_id) WHERE estado <> 'FINALIZADO';
CREATE INDEX chat_fila ON chat_atendimento(estado, setor_id, atualizado_em DESC);

CREATE TABLE chat_mensagem (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atendimento_id UUID NOT NULL REFERENCES chat_atendimento(id),
    canal_id UUID NOT NULL REFERENCES chat_canal(id),
    identificador_externo VARCHAR(200),
    sentido VARCHAR(10) NOT NULL CHECK (sentido IN ('ENTRADA', 'SAIDA')),
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('RECEBIDA', 'ENVIANDO', 'ENVIADA', 'FALHOU')),
    texto TEXT NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (canal_id, identificador_externo)
);
CREATE INDEX chat_mensagem_historico ON chat_mensagem(atendimento_id, id);

CREATE TABLE chat_acao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atendimento_id UUID NOT NULL REFERENCES chat_atendimento(id),
    ator VARCHAR(200) NOT NULL,
    tipo VARCHAR(40) NOT NULL,
    descricao TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
