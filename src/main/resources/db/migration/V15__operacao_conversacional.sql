CREATE TABLE chat_bot_definicao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresa(id),
    canal_id UUID NOT NULL,
    nome VARCHAR(100) NOT NULL,
    provedor VARCHAR(30) NOT NULL DEFAULT 'INTERNO'
        CHECK (provedor IN ('INTERNO', 'N8N')),
    ativa BOOLEAN NOT NULL DEFAULT FALSE,
    funcionamento JSONB NOT NULL DEFAULT '{"Integral":true}'::jsonb,
    fluxo JSONB NOT NULL DEFAULT '{"nodes":[],"edges":[]}'::jsonb,
    definicao JSONB,
    metadados JSONB,
    endereco_externo TEXT,
    criada_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizada_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(id, empresa_id),
    FOREIGN KEY (canal_id, empresa_id) REFERENCES chat_canal(id, empresa_id)
);
CREATE INDEX chat_bot_definicao_canal ON chat_bot_definicao(empresa_id, canal_id, ativa);

CREATE TABLE chat_bot_sessao (
    id UUID PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresa(id),
    definicao_id BIGINT NOT NULL,
    canal_id UUID NOT NULL,
    contato_id BIGINT NOT NULL,
    dados JSONB NOT NULL DEFAULT '{}'::jsonb,
    mensagens JSONB NOT NULL DEFAULT '[]'::jsonb,
    etapa VARCHAR(100),
    estado VARCHAR(20) NOT NULL DEFAULT 'ATIVA'
        CHECK (estado IN ('ATIVA', 'CONCLUIDA', 'CANCELADA')),
    criada_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizada_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (definicao_id, empresa_id) REFERENCES chat_bot_definicao(id, empresa_id),
    FOREIGN KEY (canal_id, empresa_id) REFERENCES chat_canal(id, empresa_id),
    FOREIGN KEY (contato_id, empresa_id) REFERENCES chat_contato(id, empresa_id)
);
CREATE UNIQUE INDEX chat_bot_sessao_ativa_unica ON chat_bot_sessao(canal_id, contato_id)
    WHERE estado = 'ATIVA';
CREATE INDEX chat_bot_sessao_inatividade ON chat_bot_sessao(estado, atualizada_em);

CREATE TABLE chat_token_notificacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresa(id),
    atendente_id BIGINT NOT NULL,
    resumo_token CHAR(64) NOT NULL,
    token_cifrado TEXT NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expira_em TIMESTAMPTZ,
    UNIQUE(empresa_id, resumo_token),
    FOREIGN KEY (atendente_id, empresa_id) REFERENCES chat_atendente(id, empresa_id)
);
