CREATE TABLE chat_automacao_execucao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresa(id),
    automacao_id BIGINT NOT NULL,
    mensagem_id BIGINT NOT NULL REFERENCES chat_mensagem(id),
    atendimento_id UUID NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
        CHECK (estado IN ('PENDENTE','EXECUTANDO','CONCLUIDA','FALHOU')),
    tentativas INTEGER NOT NULL DEFAULT 0,
    proxima_tentativa_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    erro TEXT,
    criada_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(automacao_id,mensagem_id),
    FOREIGN KEY (automacao_id,empresa_id) REFERENCES chat_automacao(id,empresa_id),
    FOREIGN KEY (atendimento_id,empresa_id) REFERENCES chat_atendimento(id,empresa_id)
);
CREATE INDEX chat_automacao_execucao_fila ON chat_automacao_execucao(estado,proxima_tentativa_em,id);
CREATE OR REPLACE FUNCTION chat_enfileirar_automacoes() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.sentido='ENTRADA' AND NEW.atendimento_id IS NOT NULL THEN
        INSERT INTO chat_automacao_execucao(empresa_id,automacao_id,mensagem_id,atendimento_id)
        SELECT NEW.empresa_id,id,NEW.id,NEW.atendimento_id FROM chat_automacao
        WHERE empresa_id=NEW.empresa_id AND ativa AND gatilho='MENSAGEM_RECEBIDA';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER chat_automacao_mensagem AFTER INSERT ON chat_mensagem
    FOR EACH ROW EXECUTE FUNCTION chat_enfileirar_automacoes();

