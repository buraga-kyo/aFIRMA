CREATE TABLE firma_autentica_recuperacao (
 usuario_id INTEGER PRIMARY KEY REFERENCES autentica_identidade."Usuario"(id) ON DELETE CASCADE,
 tentativas INTEGER NOT NULL DEFAULT 0,solicitada_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE firma_autentica_token_revogado (
 resumo TEXT PRIMARY KEY,expira_em TIMESTAMPTZ NOT NULL DEFAULT now()+interval '1 hour'
);
CREATE TABLE firma_autentica_ia_execucao (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 mensagem_id INTEGER NOT NULL REFERENCES autentica."Mensagem"(id) ON DELETE CASCADE,
 agente_id INTEGER NOT NULL REFERENCES autentica."InteligenciaArtificial"(id) ON DELETE CASCADE,
 estado TEXT NOT NULL DEFAULT 'PENDENTE',erro TEXT,atualizada_em TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(mensagem_id,agente_id)
);
CREATE FUNCTION firma_autentica_ia_agendar() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF NOT COALESCE(NEW."MensagemFromMe",false) AND NEW."AtendimentoId" IS NOT NULL AND NEW."MensagemTipo" IN ('Texto','TEXTO') THEN
  INSERT INTO firma_autentica_ia_execucao(mensagem_id,agente_id)
  SELECT NEW.id,ia.id FROM autentica."InteligenciaArtificial" ia JOIN autentica."Atendimento" a ON a.id=NEW."AtendimentoId"
  WHERE ia."ClienteId"=a."ClienteId" AND ia."InteligenciaArtificialStatus" AND ia."InteligenciaArtificialAtivador"='todas-mensagens'
  AND (ia."CanalId" IS NULL OR ia."CanalId"=NEW."CanalId") AND (ia."SetorId" IS NULL OR ia."SetorId"=a."SetorId") ON CONFLICT DO NOTHING;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER firma_autentica_ia_agendar AFTER INSERT ON autentica."Mensagem" FOR EACH ROW EXECUTE FUNCTION firma_autentica_ia_agendar();

