CREATE TABLE chat_envio_api (
    id UUID PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresa(id),
    canal_id UUID NOT NULL,
    contato_id BIGINT NOT NULL,
    texto TEXT NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ENVIANDO'
        CHECK (estado IN ('ENVIANDO','ENVIADO','FALHOU')),
    identificador_externo VARCHAR(200),
    erro TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    enviado_em TIMESTAMPTZ,
    FOREIGN KEY (canal_id,empresa_id) REFERENCES chat_canal(id,empresa_id),
    FOREIGN KEY (contato_id,empresa_id) REFERENCES chat_contato(id,empresa_id),
    UNIQUE(id,empresa_id)
);
ALTER TABLE chat_mensagem ADD COLUMN api_envio_id UUID UNIQUE;
ALTER TABLE chat_mensagem ADD CONSTRAINT chat_mensagem_api_envio_empresa_fk
    FOREIGN KEY (api_envio_id,empresa_id) REFERENCES chat_envio_api(id,empresa_id);
ALTER TABLE chat_mensagem DROP CONSTRAINT chat_mensagem_destino_check;
ALTER TABLE chat_mensagem ADD CONSTRAINT chat_mensagem_destino_check
    CHECK (atendimento_id IS NOT NULL OR campanha_envio_id IS NOT NULL OR api_envio_id IS NOT NULL);
CREATE TABLE chat_log_api (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresa(id),
    chave_id UUID,
    acao VARCHAR(80) NOT NULL,
    recurso_id VARCHAR(100),
    sucesso BOOLEAN NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
